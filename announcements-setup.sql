-- Linket News / Announcements setup
-- Run this entire script once in Supabase Dashboard > SQL Editor.
-- All signed-in players can read announcements. Only the Linket owner can publish.

CREATE TABLE IF NOT EXISTS public.linket_announcements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 100),
  message text NOT NULL CHECK (char_length(message) BETWEEN 1 AND 1000),
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL
);

ALTER TABLE public.linket_announcements ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Players can read Linket announcements" ON public.linket_announcements;
CREATE POLICY "Players can read Linket announcements"
ON public.linket_announcements
FOR SELECT
TO authenticated
USING (true);

REVOKE ALL ON TABLE public.linket_announcements FROM anon, public;
GRANT SELECT ON TABLE public.linket_announcements TO authenticated;

CREATE OR REPLACE FUNCTION public.linket_owner_publish_announcement(
  p_title text,
  p_message text
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $announcement$
DECLARE
  v_user_id uuid := auth.uid();
  v_id bigint;
  v_title text := btrim(COALESCE(p_title, ''));
  v_message text := btrim(COALESCE(p_message, ''));
BEGIN
  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'You must be signed in.';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.profiles p
    WHERE p.id = v_user_id AND p.is_owner = true
  ) THEN
    RAISE EXCEPTION 'Owner access only.';
  END IF;

  IF char_length(v_title) < 1 OR char_length(v_title) > 100 THEN
    RAISE EXCEPTION 'Announcement title must be 1–100 characters.';
  END IF;

  IF char_length(v_message) < 1 OR char_length(v_message) > 1000 THEN
    RAISE EXCEPTION 'Announcement message must be 1–1,000 characters.';
  END IF;

  INSERT INTO public.linket_announcements(title, message, created_by)
  VALUES (v_title, v_message, v_user_id)
  RETURNING id INTO v_id;

  RETURN v_id;
END;
$announcement$;

REVOKE ALL ON FUNCTION public.linket_owner_publish_announcement(text, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.linket_owner_publish_announcement(text, text) TO authenticated;
