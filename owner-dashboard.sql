-- Linket Owner Dashboard: secure player management and activity tools
CREATE TABLE IF NOT EXISTS public.linket_owner_activity (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  target_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  action text NOT NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.linket_owner_activity ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.linket_owner_activity FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.linket_log_token_activity()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $
BEGIN
  IF NEW.tokens IS DISTINCT FROM OLD.tokens THEN
    INSERT INTO public.linket_owner_activity(actor_id,target_id,action,details)
    VALUES(auth.uid(),NEW.id,'tokens_changed',
      jsonb_build_object('old_balance',OLD.tokens,'new_balance',NEW.tokens,'change',NEW.tokens-OLD.tokens));
  END IF;
  RETURN NEW;
END; $;

DROP TRIGGER IF EXISTS linket_log_token_activity_trigger ON public.profiles;
CREATE TRIGGER linket_log_token_activity_trigger
AFTER UPDATE OF tokens ON public.profiles
FOR EACH ROW EXECUTE FUNCTION public.linket_log_token_activity();

CREATE OR REPLACE FUNCTION public.linket_log_collectible_activity()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $
BEGIN
  INSERT INTO public.linket_owner_activity(actor_id,target_id,action,details)
  VALUES(auth.uid(),NEW.user_id,
    CASE WHEN TG_OP='INSERT' THEN 'collectible_added' ELSE 'collectible_quantity_changed' END,
    jsonb_build_object('collectible',NEW.collectible_id,'quantity',NEW.quantity));
  RETURN NEW;
END; $;

DROP TRIGGER IF EXISTS linket_log_collectible_activity_trigger ON public.owned_collectibles;
CREATE TRIGGER linket_log_collectible_activity_trigger
AFTER INSERT OR UPDATE OF quantity ON public.owned_collectibles
FOR EACH ROW EXECUTE FUNCTION public.linket_log_collectible_activity();

CREATE OR REPLACE FUNCTION public.linket_owner_list_players()
RETURNS TABLE(
  player_id uuid,
  username text,
  tokens bigint,
  is_owner boolean,
  created_at timestamptz,
  collectible_count bigint
)
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.profiles p WHERE p.id=auth.uid() AND p.is_owner=true
  ) THEN RAISE EXCEPTION 'Owner access only.'; END IF;

  RETURN QUERY
  SELECT p.id,p.username,p.tokens,p.is_owner,p.created_at,
         COUNT(DISTINCT oc.collectible_id)::bigint
  FROM public.profiles p
  LEFT JOIN public.owned_collectibles oc ON oc.user_id=p.id
  GROUP BY p.id,p.username,p.tokens,p.is_owner,p.created_at
  ORDER BY p.created_at DESC;
END; $$;

CREATE OR REPLACE FUNCTION public.linket_owner_adjust_tokens(p_user_id uuid,p_amount bigint)
RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_actor uuid:=auth.uid(); v_balance bigint;
BEGIN
  IF v_actor IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.profiles p WHERE p.id=v_actor AND p.is_owner=true
  ) THEN RAISE EXCEPTION 'Owner access only.'; END IF;
  IF p_amount=0 OR abs(p_amount)>1000000000 THEN RAISE EXCEPTION 'Enter a non-zero token adjustment within 1 billion.'; END IF;

  UPDATE public.profiles p
  SET tokens=p.tokens+p_amount
  WHERE p.id=p_user_id AND p.tokens+p_amount>=0
  RETURNING p.tokens INTO v_balance;
  IF NOT FOUND THEN RAISE EXCEPTION 'Player not found or adjustment would make tokens negative.'; END IF;

  RETURN v_balance;
END; $$;

CREATE OR REPLACE FUNCTION public.linket_owner_grant_collectible(p_user_id uuid,p_collectible_id text,p_quantity integer DEFAULT 1)
RETURNS integer
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_actor uuid:=auth.uid(); v_new_quantity integer;
BEGIN
  IF v_actor IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.profiles p WHERE p.id=v_actor AND p.is_owner=true
  ) THEN RAISE EXCEPTION 'Owner access only.'; END IF;
  IF p_quantity<1 OR p_quantity>1000 THEN RAISE EXCEPTION 'Quantity must be between 1 and 1000.'; END IF;
  IF p_collectible_id NOT IN ('Happy Turtle','Tiny Bee','Bouncy Bunny','Robot Buddy','Frost Wolf','Golden Owl','Crystal Cat','Lumi Fox','Galaxy Dragon','Starwing') THEN
    RAISE EXCEPTION 'Unknown collectible.';
  END IF;
  INSERT INTO public.owned_collectibles(user_id,collectible_id,quantity)
  VALUES(p_user_id,p_collectible_id,p_quantity)
  ON CONFLICT(user_id,collectible_id)
  DO UPDATE SET quantity=public.owned_collectibles.quantity+EXCLUDED.quantity
  RETURNING quantity INTO v_new_quantity;
  IF NOT FOUND THEN RAISE EXCEPTION 'Player not found.'; END IF;

  RETURN v_new_quantity;
END; $$;

CREATE OR REPLACE FUNCTION public.linket_owner_recent_activity(p_limit integer DEFAULT 30)
RETURNS TABLE(
  activity_id bigint,
  actor_username text,
  target_username text,
  action text,
  details jsonb,
  created_at timestamptz
)
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.profiles p WHERE p.id=auth.uid() AND p.is_owner=true
  ) THEN RAISE EXCEPTION 'Owner access only.'; END IF;
  RETURN QUERY
  SELECT a.id,actor.username,target.username,a.action,a.details,a.created_at
  FROM public.linket_owner_activity a
  LEFT JOIN public.profiles actor ON actor.id=a.actor_id
  LEFT JOIN public.profiles target ON target.id=a.target_id
  ORDER BY a.created_at DESC LIMIT LEAST(GREATEST(COALESCE(p_limit,30),1),100);
END; $$;

REVOKE ALL ON FUNCTION public.linket_owner_list_players() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.linket_owner_adjust_tokens(uuid,bigint) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.linket_owner_grant_collectible(uuid,text,integer) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.linket_owner_recent_activity(integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.linket_owner_list_players() TO authenticated;
GRANT EXECUTE ON FUNCTION public.linket_owner_adjust_tokens(uuid,bigint) TO authenticated;
GRANT EXECUTE ON FUNCTION public.linket_owner_grant_collectible(uuid,text,integer) TO authenticated;
GRANT EXECUTE ON FUNCTION public.linket_owner_recent_activity(integer) TO authenticated;
