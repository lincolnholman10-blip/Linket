DROP FUNCTION IF EXISTS public.linket_owner_list_players();
CREATE FUNCTION public.linket_owner_list_players()
RETURNS TABLE(
  player_id uuid,
  username text,
  tokens bigint,
  is_owner boolean,
  created_at timestamptz,
  collectible_count bigint,
  is_banned boolean
)
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.profiles p WHERE p.id=auth.uid() AND p.is_owner=true
  ) THEN RAISE EXCEPTION 'Owner access only.'; END IF;

  RETURN QUERY
  SELECT p.id,p.username,p.tokens,p.is_owner,p.created_at,
         COUNT(DISTINCT oc.collectible_id)::bigint,p.is_banned
  FROM public.profiles p
  LEFT JOIN public.owned_collectibles oc ON oc.user_id=p.id
  GROUP BY p.id,p.username,p.tokens,p.is_owner,p.created_at,p.is_banned
  ORDER BY p.created_at DESC;
END; $$;

CREATE OR REPLACE FUNCTION public.linket_owner_rename_player(p_user_id uuid,p_username text)
RETURNS text
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_name text:=btrim(p_username);
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.profiles WHERE id=auth.uid() AND is_owner=true
  ) THEN RAISE EXCEPTION 'Owner access only.'; END IF;
  IF v_name IS NULL OR length(v_name)<3 OR length(v_name)>24 OR v_name !~ '^[A-Za-z0-9_ -]+$' THEN
    RAISE EXCEPTION 'Username must be 3–24 characters and use only letters, numbers, spaces, _ or -.';
  END IF;
  UPDATE public.profiles SET username=v_name WHERE id=p_user_id AND is_owner=false;
  IF NOT FOUND THEN RAISE EXCEPTION 'Player not found. Owner usernames cannot be changed here.'; END IF;
  INSERT INTO public.linket_owner_activity(actor_id,target_id,action,details)
  VALUES(auth.uid(),p_user_id,'username_changed',jsonb_build_object('new_username',v_name));
  RETURN v_name;
END; $$;

CREATE OR REPLACE FUNCTION public.linket_owner_set_banned(p_user_id uuid,p_banned boolean)
RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.profiles WHERE id=auth.uid() AND is_owner=true
  ) THEN RAISE EXCEPTION 'Owner access only.'; END IF;
  IF p_user_id=auth.uid() OR EXISTS (SELECT 1 FROM public.profiles WHERE id=p_user_id AND is_owner=true) THEN
    RAISE EXCEPTION 'You cannot ban the owner account.';
  END IF;
  UPDATE auth.users SET banned_until=CASE WHEN p_banned THEN 'infinity'::timestamptz ELSE NULL END
  WHERE id=p_user_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Authentication account not found.'; END IF;
  UPDATE public.profiles SET is_banned=p_banned WHERE id=p_user_id;
  INSERT INTO public.linket_owner_activity(actor_id,target_id,action,details)
  VALUES(auth.uid(),p_user_id,CASE WHEN p_banned THEN 'player_banned' ELSE 'player_unbanned' END,'{}'::jsonb);
  RETURN p_banned;
END; $$;

CREATE OR REPLACE FUNCTION public.linket_owner_delete_player(p_user_id uuid)
RETURNS boolean
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.profiles WHERE id=auth.uid() AND is_owner=true
  ) THEN RAISE EXCEPTION 'Owner access only.'; END IF;
  IF p_user_id=auth.uid() OR EXISTS (SELECT 1 FROM public.profiles WHERE id=p_user_id AND is_owner=true) THEN
    RAISE EXCEPTION 'You cannot delete the owner account.';
  END IF;
  DELETE FROM auth.users WHERE id=p_user_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Player account not found.'; END IF;
  INSERT INTO public.linket_owner_activity(actor_id,target_id,action,details)
  VALUES(auth.uid(),p_user_id,'player_deleted','{}'::jsonb);
  RETURN true;
END; $$;

CREATE OR REPLACE FUNCTION public.linket_owner_publish_announcement(p_title text,p_message text)
RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_id bigint;
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (
    SELECT 1 FROM public.profiles WHERE id=auth.uid() AND is_owner=true
  ) THEN RAISE EXCEPTION 'Owner access only.'; END IF;
  IF length(btrim(p_title)) NOT BETWEEN 1 AND 100 OR length(btrim(p_message)) NOT BETWEEN 1 AND 1000 THEN
    RAISE EXCEPTION 'Announcement title or message is too long or empty.';
  END IF;
  INSERT INTO public.linket_announcements(title,message,created_by)
  VALUES(btrim(p_title),btrim(p_message),auth.uid()) RETURNING id INTO v_id;
  INSERT INTO public.linket_owner_activity(actor_id,action,details)
  VALUES(auth.uid(),'announcement_published',jsonb_build_object('announcement_id',v_id,'title',btrim(p_title)));
  RETURN v_id;
END; $$;

